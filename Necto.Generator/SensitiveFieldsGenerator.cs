using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
namespace Necto.Generator;
[Generator]
public sealed class SensitiveFieldsGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var types=ContractSymbols.Types(context);
        context.RegisterSourceOutput(types.Combine(GeneratedScope.For(context,"SensitiveFields")),static(ctx,data)=>{
            var items=data.Left;
            var code=new StringBuilder("// <auto-generated/>\nnamespace Necto; internal static class GeneratedSensitiveFields { internal static Microsoft.AspNetCore.OpenApi.OpenApiOptions AddNectoGeneratedSensitiveFields(this Microsoft.AspNetCore.OpenApi.OpenApiOptions options) => NectoSensitiveMetadata.Add(options,new NectoSensitiveField[] {\n");
            foreach(var type in items.OfType<INamedTypeSymbol>().GroupBy(ContractSymbols.ClrName).Select(group=>group.First()).OrderBy(ContractSymbols.ClrName,StringComparer.Ordinal))
            foreach(var property in ContractSymbols.Properties(type).Where(property=>ContractSymbols.Attribute(property,"Necto.NectoSensitiveAttribute") is not null))
                code.AppendLine($"new({ContractSymbols.Literal(ContractSymbols.ClrName(type))},{ContractSymbols.Literal(property.Name)}),");
            code.AppendLine("}); }");ctx.AddSource("NectoSensitiveFields.g.cs",GeneratedScope.Isolate(code.ToString(),data.Right));
        });
    }
}
