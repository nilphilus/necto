using System.Security.Cryptography;
using System.Text;
using Microsoft.CodeAnalysis;
namespace Necto.Generator;
internal static class GeneratedScope
{
    internal static IncrementalValueProvider<string> For(IncrementalGeneratorInitializationContext context,string feature) =>
        context.CompilationProvider.Select((compilation,_)=>Namespace(compilation.Assembly.Identity.ToString(),feature));
    internal static string Namespace(string identity,string feature)
    {
        using var hash=SHA256.Create();
        var bytes=hash.ComputeHash(Encoding.UTF8.GetBytes(identity));
        var suffix=string.Concat(bytes.Select(value=>value.ToString("x2",System.Globalization.CultureInfo.InvariantCulture)));
        return "Necto.Generated.Assembly_"+suffix+"."+feature;
    }
    internal static string Isolate(string source,string scope,bool import=true) =>
        source.Replace("// <auto-generated/>","// <auto-generated/>\n"+(import?"global using global::"+scope+";\n":"")+"using global::Necto;")
            .Replace("namespace Necto;","namespace "+scope+";")
            .Replace("[assembly: Necto.GeneratedNectoMappings]","[assembly: global::"+scope+".GeneratedNectoMappings]");
}
