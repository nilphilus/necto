using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Necto.Generator;

public sealed partial class EndpointMappingGenerator
{
    private static Endpoint? ReadFastEndpoint(GeneratorSyntaxContext context, CancellationToken cancellationToken)
    {
        var declaration = (TypeDeclarationSyntax)context.Node;
        if (context.SemanticModel.GetDeclaredSymbol(declaration, cancellationToken) is not INamedTypeSymbol
            { TypeKind: TypeKind.Class, IsAbstract: false } type)
            return null;
        if (type.DeclaringSyntaxReferences.FirstOrDefault(reference =>
                reference.GetSyntax(cancellationToken) is TypeDeclarationSyntax { BaseList: not null }) is { } first
            && (first.SyntaxTree != declaration.SyntaxTree || first.Span != declaration.Span))
            return null;
        for (var containing = type; containing is not null; containing = containing.ContainingType)
        {
            if (containing.Arity != 0 || containing.IsFileLocal ||
                containing.DeclaredAccessibility is not (Accessibility.Public or Accessibility.Internal or Accessibility.ProtectedOrInternal))
                return null;
        }

        var compilation = context.SemanticModel.Compilation;
        var baseType = compilation.GetTypeByMetadataName("FastEndpoints.Endpoint`2");
        if (baseType is null || compilation.GetTypeByMetadataName("FastEndpoints.EndpointDefinition")?
            .GetMembers("EndpointType").Length is not > 0)
            return null;

        for (var current = type.BaseType; current is not null; current = current.BaseType)
        {
            if (!SymbolEqualityComparer.Default.Equals(current.OriginalDefinition, baseType))
                continue;
            var name = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            return new Endpoint("\0" + name, ReadResponse(current.TypeArguments[1]).ToArray(),
                ReadFastRequest(current.TypeArguments[0]).ToArray(), name);
        }
        return null;
    }

    private static IEnumerable<Field> ReadFastRequest(ITypeSymbol type)
    {
        foreach (var property in JsonProperties(type).Where(property => property.SetMethod?.DeclaredAccessibility == Accessibility.Public))
        {
            var propertyType = NonNullable(property.Type);
            var binding = property.GetAttributes().Select(attribute => attribute.AttributeClass?.ToDisplayString()).ToArray();
            if (binding.Any(name => name is "FastEndpoints.FromClaimAttribute" or "FastEndpoints.FromAttributeAttribute"
                or "FastEndpoints.FromCookieAttribute" or "FastEndpoints.FormFieldAttribute" or "FastEndpoints.DontBindAttribute"))
                continue;
            var key = ValueKey(property);
            if (binding.Contains("FastEndpoints.FromBodyAttribute"))
            {
                if (IsScalar(propertyType) || IsTypedId(propertyType) || key is not null)
                    yield return new Field(propertyType, null, property.Name, key, "body");
                else
                    foreach (var child in JsonProperties(propertyType))
                        yield return new Field(NonNullable(child.Type), JsonName(child), child.Name,
                            ValueKey(child), "body", Owner: propertyType.ToDisplayString());
                continue;
            }
            if (binding.Contains("FastEndpoints.FromQueryAttribute") && !IsScalar(propertyType) && !IsTypedId(propertyType))
                continue;

            var location = binding.Contains("FastEndpoints.RouteParamAttribute") ? "path"
                : binding.Contains("FastEndpoints.FromHeaderAttribute") ? "header"
                : binding.Contains("FastEndpoints.QueryParamAttribute") || binding.Contains("FastEndpoints.FromQueryAttribute") ? "query"
                : "fast-property";
            var bindingName = AttributeString(property, "FastEndpoints.FromHeaderAttribute")
                ?? AttributeString(property, "FastEndpoints.BindFromAttribute") ?? JsonName(property);
            yield return new Field(propertyType, bindingName, property.Name, key, location, Owner: type.ToDisplayString());
        }
    }

    private static void EmitFastEndpointRoutes(SourceProductionContext context, Endpoint[] endpoints)
    {
        var fastEndpoints = endpoints.Where(endpoint => endpoint.FastEndpointType is not null).ToArray();
        if (fastEndpoints.Length == 0)
            return;

        var code = new StringBuilder("""
            // <auto-generated/>
            #nullable enable
            using System;
            using System.Collections.Generic;
            using System.Linq;
            using Microsoft.AspNetCore.Http;
            using Microsoft.AspNetCore.Http.Metadata;
            using Microsoft.AspNetCore.Routing;

            namespace Necto;

            internal static class NectoFastEndpointRoutes
            {
                private static readonly Dictionary<Type, string> Contracts = new()
                {

            """);
        foreach (var endpoint in fastEndpoints)
            code.AppendLine($"        [typeof({endpoint.FastEndpointType})] = {Literal(endpoint.Id)},");
        code.AppendLine("""
                };

                private sealed record Operation(string Id, RouteEndpoint? Route = null);

                private static ILookup<string, Operation> ReadRoutes(IEnumerable<EndpointDataSource> dataSources) =>
                    dataSources.SelectMany(source => source.Endpoints).OfType<RouteEndpoint>()
                        .Where(route => route.Metadata.GetMetadata<IExcludeFromDescriptionMetadata>()?.ExcludeFromDescription != true)
                        .Select(route => (Route: route,
                            Definition: route.Metadata.GetMetadata<global::FastEndpoints.EndpointDefinition>(),
                            Name: route.Metadata.GetMetadata<IEndpointNameMetadata>()?.EndpointName))
                        .Where(item => item.Name is not null && item.Definition is not null
                            && Contracts.ContainsKey(item.Definition.EndpointType))
                        .ToLookup(item => Contracts[item.Definition!.EndpointType], item => new Operation(item.Name!, item.Route));

                private static IEnumerable<Operation> Resolve(ILookup<string, Operation> routes, string id) =>
                    id.Length > 0 && id[0] == '\0' ? routes[id] : new[] { new Operation(id) };

                private static RequestValue? ResolveTarget(Operation operation, RequestValue target)
                {
                    var route = operation.Route;
                    if (route is null)
                        return target;
                    if (target.Location is "path" or "fast-property")
                    {
                        var parameter = route.RoutePattern.Parameters.FirstOrDefault(parameter =>
                            string.Equals(parameter.Name, target.Name, StringComparison.OrdinalIgnoreCase));
                        if (parameter is not null)
                            return target with { OperationId = operation.Id, Location = "path", Name = parameter.Name };
                        if (target.Location == "path")
                            return null;
                    }
                    var location = target.Location == "fast-property"
                        ? route.Metadata.GetMetadata<IHttpMethodMetadata>()?.HttpMethods.All(method =>
                            HttpMethods.IsGet(method) || HttpMethods.IsHead(method) ||
                            HttpMethods.IsDelete(method) || HttpMethods.IsOptions(method)) == true ? "query" : "body"
                        : target.Location;
                    return target with { OperationId = operation.Id, Location = location };
                }

                internal static EndpointMapping[] ResolveMappings(IEnumerable<EndpointDataSource> dataSources, EndpointMapping[] mappings)
                {
                    var routes = ReadRoutes(dataSources);
                    return (from mapping in mappings
                            from source in Resolve(routes, mapping.Source.OperationId)
                            from operation in Resolve(routes, mapping.Target.OperationId)
                            let target = ResolveTarget(operation, mapping.Target)
                            where target is not null
                            select mapping with { Source = mapping.Source with { OperationId = source.Id }, Target = target }).ToArray();
                }

                internal static EntityCatalogEntry[] ResolveCatalog(IEnumerable<EndpointDataSource> dataSources, EntityCatalogEntry[] catalog)
                {
                    var routes = ReadRoutes(dataSources);
                    return catalog.Select(entry => entry with
                    {
                        Uses = (from use in entry.Uses
                                from operation in Resolve(routes, use.OperationId)
                                let last = use.Path.LastOrDefault()
                                let target = use.Direction == "request"
                                    ? ResolveTarget(operation, new RequestValue(use.OperationId, use.Location, last))
                                    : null
                                where use.Direction == "response" || target is not null
                                select use with
                                {
                                    OperationId = operation.Id,
                                    Location = target?.Location ?? use.Location,
                                    Path = last is not null && target?.Name is string name && name != last
                                        ? use.Path.Take(use.Path.Length - 1).Append(name).ToArray() : use.Path,
                                }).ToArray(),
                    }).Where(entry => entry.Uses.Length > 0).ToArray();
                }
            }
            """);
        context.AddSource("FastEndpointRoutes.g.cs", code.ToString());
    }
}
