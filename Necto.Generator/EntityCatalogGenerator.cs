using System.Text;
using Microsoft.CodeAnalysis;
namespace Necto.Generator;
public sealed partial class EndpointMappingGenerator
{
    private static void EmitEntityCatalog(SourceProductionContext context, Endpoint[] endpoints, bool hasFastEndpoints, string scope)
    {
        var uses = new List<CatalogUse>();
        foreach (var endpoint in endpoints)
        foreach (var direction in new[] { "response", "request" })
        foreach (var field in direction == "response" ? endpoint.Response : endpoint.Request)
        {
            var container = direction == "response" ? field.ObjectPath ?? (field.EachItem ? new string?[] { null } : Array.Empty<string?>()) : Array.Empty<string?>();
            if (field.Owner is not null)
                uses.Add(new("model:" + field.Owner, field.Owner, "model", endpoint.Id, direction, direction == "response" ? "body" : field.Location, container));
            var logical = field.Key ?? IdentifierName(field.ConventionName ?? "") ?? IdentifierName(field.WireName ?? "");
            if (logical is null && field.Owner is not null && SameName(field.WireName, "Id")) logical = field.Owner.Split('.').Last() + "Id";
            if (!IsTypedId(field.Type) && (!IsScalar(field.Type) || logical is null)) continue;
            var name = IsTypedId(field.Type) ? field.Type.ToDisplayString() : char.ToUpperInvariant(logical![0]) + logical.Substring(1);
            var id = "identifier:" + (IsTypedId(field.Type) ? name : name.ToUpperInvariant()) + ":" + field.Type.ToDisplayString();
            var path = container.Concat(field.WireName is null ? Array.Empty<string?>() : new string?[] { field.WireName }).ToArray();
            uses.Add(new(id, name, "identifier", endpoint.Id, direction, direction == "response" ? "body" : field.Location, path));
        }
        var code = new StringBuilder("""
            // <auto-generated/>
            #nullable enable
            using Microsoft.AspNetCore.Builder;
            using Microsoft.AspNetCore.Http;
            using Microsoft.AspNetCore.Routing;
            namespace Necto;
            internal static class GeneratedEntityCatalog
            {
                private static readonly EntityCatalogEntry[] Catalog = {
            """);
        foreach (var group in uses.GroupBy(use => use.Id).OrderBy(group => group.Key, StringComparer.Ordinal))
        {
            var item = group.First();
            code.AppendLine($"new({Literal(item.Id)}, {Literal(item.Name)}, {Literal(item.Kind)}, new EntityCatalogUse[] {{");
            foreach (var use in group.GroupBy(use => use.OperationId + "|" + use.Direction + "|" + use.Location + "|" + string.Join("/", use.Path.Select(part => part ?? "[]"))).Select(group => group.First()))
                code.AppendLine($"new({Literal(use.OperationId)}, {Literal(use.Direction)}, {Literal(use.Location)}, new string?[] {{ {string.Join(", ", use.Path.Select(Literal))} }}),");
            code.AppendLine("}),");
        }
        var catalog = hasFastEndpoints ? "NectoFastEndpointRoutes.ResolveCatalog(endpoints.DataSources, Catalog)" : "Catalog";
        code.AppendLine($$"""
                };
                internal static RouteHandlerBuilder MapNectoEntityCatalog(this IEndpointRouteBuilder endpoints, string pattern = "/necto/entity-catalog") =>
                    NectoGeneratedMetadata.Register(endpoints, endpoints.MapGet(pattern, () => Results.Json({{catalog}}, System.Text.Json.JsonSerializerOptions.Web)).ExcludeFromDescription(), "entityCatalogUrl");
            }
            """);
        context.AddSource("EntityCatalog.g.cs", GeneratedScope.Isolate(code.ToString(),scope,false));
    }
    private sealed record CatalogUse(string Id, string Name, string Kind, string OperationId, string Direction, string Location, string?[] Path);
}
