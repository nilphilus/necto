using System.Globalization;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
namespace Necto.Generator;
[Generator]
public sealed class FieldConstraintsGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var types=context.SyntaxProvider.CreateSyntaxProvider(static(node,_)=>node is TypeDeclarationSyntax,static(ctx,ct)=>ctx.SemanticModel.GetDeclaredSymbol((TypeDeclarationSyntax)ctx.Node,ct) as INamedTypeSymbol).Where(static type=>type is not null);
        context.RegisterSourceOutput(types.Collect(),static(ctx,items)=>{
            var code=new StringBuilder("// <auto-generated/>\nnamespace Necto; internal static class GeneratedFieldConstraints { internal static Microsoft.AspNetCore.OpenApi.OpenApiOptions AddNectoGeneratedConstraints(this Microsoft.AspNetCore.OpenApi.OpenApiOptions options) => NectoFieldConstraints.Add(options,new NectoFieldConstraint[] {\n");
            foreach(var type in items.OfType<INamedTypeSymbol>().GroupBy(ContractSymbols.ClrName).Select(group=>group.First()).OrderBy(ContractSymbols.ClrName,StringComparer.Ordinal))
            foreach(var property in ContractSymbols.Properties(type))
            foreach(var attribute in property.GetAttributes())
            {
                if(attribute.AttributeClass?.ContainingNamespace.ToDisplayString()!="System.ComponentModel.DataAnnotations")continue;
                var kind=attribute.AttributeClass.Name;
                if(kind is not ("RequiredAttribute" or "RangeAttribute" or "StringLengthAttribute" or "MinLengthAttribute" or "MaxLengthAttribute" or "EmailAddressAttribute" or "UrlAttribute" or "RegularExpressionAttribute"))continue;
                string? Value(int index)=>attribute.ConstructorArguments.Length>index?Convert.ToString(attribute.ConstructorArguments[index].Value,CultureInfo.InvariantCulture):null;
                if(kind=="RangeAttribute" && attribute.NamedArguments.Any(item=>item.Key is "MinimumIsExclusive" or "MaximumIsExclusive" && item.Value.Value is true))continue;
                var first=Value(0);var second=Value(1);
                if(kind=="RangeAttribute"&&attribute.ConstructorArguments.Length==3){first=Value(1);second=Value(2);}
                if(kind=="StringLengthAttribute")second=Convert.ToString(attribute.NamedArguments.FirstOrDefault(item=>item.Key=="MinimumLength").Value.Value,CultureInfo.InvariantCulture);
                code.AppendLine($"new({ContractSymbols.Literal(ContractSymbols.ClrName(type))},{ContractSymbols.Literal(property.Name)},{ContractSymbols.Literal(kind)},{ContractSymbols.Literal(first)},{ContractSymbols.Literal(second)}),");
            }
            code.AppendLine("}); }");ctx.AddSource("NectoFieldConstraints.g.cs",code.ToString());
        });
    }
}
