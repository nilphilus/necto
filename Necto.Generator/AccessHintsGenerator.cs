using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Operations;
namespace Necto.Generator;
[Generator]
public sealed class AccessHintsGenerator:IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var endpoints=context.SyntaxProvider.CreateSyntaxProvider(
            static(node,_)=>node is InvocationExpressionSyntax{Expression:MemberAccessExpressionSyntax{Name.Identifier.ValueText:"WithName"}},
            static(ctx,ct)=>Read(ctx,ct)).Where(static item=>item is not null);
        context.RegisterSourceOutput(endpoints.Collect(),static(ctx,items)=>Emit(ctx,items.OfType<AccessEndpoint>().ToArray()));
    }
    private static AccessEndpoint? Read(GeneratorSyntaxContext context,CancellationToken token)
    {
        var invocation=(InvocationExpressionSyntax)context.Node;var model=context.SemanticModel;
        if(model.GetOperation(invocation,token) is not IInvocationOperation named||named.TargetMethod.ContainingType.ToDisplayString()!="Microsoft.AspNetCore.Builder.RoutingEndpointConventionBuilderExtensions"||named.Arguments.FirstOrDefault(arg=>arg.Parameter?.Name=="endpointName")?.Value.ConstantValue is not{HasValue:true,Value:string id})return null;
        ExpressionSyntax receiver=((MemberAccessExpressionSyntax)invocation.Expression).Expression;
        while(receiver is InvocationExpressionSyntax call&&call.Expression is MemberAccessExpressionSyntax member)
        {
            if(model.GetOperation(call,token) is IInvocationOperation route&&route.TargetMethod.ContainingType.ToDisplayString()=="Microsoft.AspNetCore.Builder.EndpointRouteBuilderExtensions")
            {
                var value=route.Arguments.FirstOrDefault(arg=>arg.Parameter?.Name=="handler")?.Value;
                while(value is IConversionOperation conversion)value=conversion.Operand;
                var handler=value is IDelegateCreationOperation creation?creation.Target switch{IAnonymousFunctionOperation lambda=>lambda.Symbol,IMethodReferenceOperation reference=>reference.Method,_=>null}:null;
                return handler is null?null:new(id,handler);
            }
            receiver=member.Expression;
        }
        return null;
    }
    private static void Emit(SourceProductionContext context,AccessEndpoint[] endpoints)
    {
        var code=new StringBuilder("// <auto-generated/>\nnamespace Necto; internal static class GeneratedAccessHints { internal static Microsoft.AspNetCore.OpenApi.OpenApiOptions AddNectoGeneratedAccessHints(this Microsoft.AspNetCore.OpenApi.OpenApiOptions options) => NectoAccessHints.Add(options,new NectoAccessDeclaration[] {\n");
        foreach(var endpoint in endpoints.GroupBy(item=>item.Id).Where(group=>group.Count()==1).Select(group=>group.Single()).OrderBy(item=>item.Id,StringComparer.Ordinal))
        {
            var attributes=endpoint.Handler.GetAttributes();
            var anonymous=attributes.Any(item=>item.AttributeClass?.ToDisplayString()=="Microsoft.AspNetCore.Authorization.AllowAnonymousAttribute");
            code.AppendLine($"new({ContractSymbols.Literal(endpoint.Id)}, {(anonymous?"true":"false")},new NectoAccessRule[] {{");
            foreach(var attribute in attributes.Where(item=>item.AttributeClass?.ToDisplayString()=="Microsoft.AspNetCore.Authorization.AuthorizeAttribute"))
            {
                string? Named(string key)=>attribute.NamedArguments.FirstOrDefault(item=>item.Key==key).Value.Value as string;
                var policy=Named("Policy")??attribute.ConstructorArguments.FirstOrDefault().Value as string;
                code.AppendLine($"new({ContractSymbols.Literal(policy)},{ContractSymbols.Literal(Named("Roles"))},{ContractSymbols.Literal(Named("AuthenticationSchemes"))}),");
            }
            code.AppendLine("}),");
        }
        code.AppendLine("}); }");context.AddSource("NectoAccessHints.g.cs",code.ToString());
    }
    private sealed record AccessEndpoint(string Id,IMethodSymbol Handler);
}
