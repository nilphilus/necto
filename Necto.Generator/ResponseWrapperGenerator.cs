using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
namespace Necto.Generator;
[Generator]
public sealed class ResponseWrapperGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var types = context.SyntaxProvider.CreateSyntaxProvider(static (node,_) => node is TypeDeclarationSyntax,
            static (ctx,ct) => ctx.SemanticModel.GetDeclaredSymbol((TypeDeclarationSyntax)ctx.Node,ct) as INamedTypeSymbol).Where(static type => type is not null);
        context.RegisterSourceOutput(types.Collect(),static (ctx,items) => {
            var code = new StringBuilder("// <auto-generated/>\nnamespace Necto;\ninternal static class GeneratedResponseWrappers { internal static Microsoft.AspNetCore.OpenApi.OpenApiOptions AddNectoGeneratedWrappers(this Microsoft.AspNetCore.OpenApi.OpenApiOptions options) => NectoResponseWrappers.Add(options, new NectoResponseWrapper[] {\n");
            foreach(var type in items.OfType<INamedTypeSymbol>().GroupBy(ContractSymbols.ClrName).Select(group=>group.First()).OrderBy(ContractSymbols.ClrName,StringComparer.Ordinal))
            {
                var properties = ContractSymbols.Properties(type).ToArray();
                var attribute = ContractSymbols.Attribute(type,"Necto.NectoResponseCollectionAttribute");
                var explicitName = attribute?.ConstructorArguments.FirstOrDefault().Value as string;
                var collections = properties.Where(property=>ContractSymbols.Collection(property.Type)).ToArray();
                var collection = explicitName is not null ? collections.FirstOrDefault(property=>property.Name==explicitName) :
                    type.Name is "PagedResult" or "PagedResponse" or "PageResult" && collections.Length==1 ? collections[0] : null;
                if(collection is null)continue;
                var count = attribute?.NamedArguments.FirstOrDefault(item=>item.Key=="TotalCountProperty").Value.Value as string ?? (properties.Any(property=>property.Name=="TotalCount")?"TotalCount":null);
                code.AppendLine($"new({ContractSymbols.Literal(ContractSymbols.ClrName(type))},{ContractSymbols.Literal(collection.Name)},{ContractSymbols.Literal(count)}),");
            }
            code.AppendLine("}); }");ctx.AddSource("NectoResponseWrappers.g.cs",code.ToString());
        });
    }
}
