using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Operations;
namespace Necto.Generator;
[Generator]
public sealed class OperationRolesGenerator:IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var endpoints=context.SyntaxProvider.CreateSyntaxProvider(
            static(node,_)=>node is InvocationExpressionSyntax{Expression:MemberAccessExpressionSyntax{Name.Identifier.ValueText:"WithName"}},
            static(ctx,ct)=>Read(ctx,ct)).Where(static item=>item is not null);
        context.RegisterSourceOutput(endpoints.Collect(),static(ctx,items)=>{
            var code=new StringBuilder("""
                // <auto-generated/>
                #nullable enable
                using Microsoft.AspNetCore.Builder;
                using Microsoft.AspNetCore.Http;
                using Microsoft.AspNetCore.Routing;
                namespace Necto;
                internal static class GeneratedOperationRoles
                {
                    private static readonly NectoOperationPurpose[] Roles = {
                """);
            foreach(var endpoint in items.OfType<RoleEndpoint>().GroupBy(item=>item.Id).Where(group=>group.Count()==1).Select(group=>group.Single()).OrderBy(item=>item.Id,StringComparer.Ordinal))
            foreach(var role in endpoint.Roles.GroupBy(role=>role.Entity+"|"+role.RoleName).Select(group=>group.First()))
                code.AppendLine($"new({Literal(endpoint.Id)}, {Literal(role.Entity)}, {Literal(role.Name)}, {Literal(role.RoleName)}, {Literal(role.Description)}),");
            code.AppendLine("""
                    };
                    internal static RouteHandlerBuilder MapNectoOperationRoles(this IEndpointRouteBuilder endpoints,string pattern="/necto/operation-roles") =>
                        NectoGeneratedMetadata.Register(endpoints,endpoints.MapGet(pattern,()=>Results.Json(Roles,System.Text.Json.JsonSerializerOptions.Web)).ExcludeFromDescription(),"operationRolesUrl");
                }
                """);
            ctx.AddSource("OperationRoles.g.cs",code.ToString());
        });
    }
    private static string Literal(string? value)=>value is null?"null":SymbolDisplay.FormatLiteral(value,true);
    private static RoleEndpoint? Read(GeneratorSyntaxContext context,CancellationToken token)
    {
        var invocation=(InvocationExpressionSyntax)context.Node;var model=context.SemanticModel;
        if(model.GetOperation(invocation,token) is not IInvocationOperation named||named.TargetMethod.ContainingType.ToDisplayString()!="Microsoft.AspNetCore.Builder.RoutingEndpointConventionBuilderExtensions"||named.Arguments.FirstOrDefault(arg=>arg.Parameter?.Name=="endpointName")?.Value.ConstantValue is not{HasValue:true,Value:string id})return null;
        ExpressionSyntax receiver=((MemberAccessExpressionSyntax)invocation.Expression).Expression;
        while(receiver is InvocationExpressionSyntax call&&call.Expression is MemberAccessExpressionSyntax member)
        {
            if(model.GetOperation(call,token) is IInvocationOperation route&&route.TargetMethod.ContainingType.ToDisplayString()=="Microsoft.AspNetCore.Builder.EndpointRouteBuilderExtensions")
            {
                var value=route.Arguments.FirstOrDefault(arg=>arg.Parameter?.Name=="handler")?.Value;
                while(value is IConversionOperation conversion)value=conversion.Operand;
                var method=value is IDelegateCreationOperation creation?creation.Target switch{IAnonymousFunctionOperation lambda=>lambda.Symbol,IMethodReferenceOperation reference=>reference.Method,_=>null}:null;
                var roles=new List<Role>();
                foreach(var attribute in method?.GetAttributes().ToArray()??Array.Empty<AttributeData>())
                {
                    if(attribute.AttributeClass?.ToDisplayString()!="Necto.NectoOperationAttribute"||attribute.ConstructorArguments.Length!=2||attribute.ConstructorArguments[0].Value is not ITypeSymbol entity)continue;
                    var roleValue=attribute.ConstructorArguments[1];
                    var role=roleValue.Type?.GetMembers().OfType<IFieldSymbol>().FirstOrDefault(field=>field.HasConstantValue&&Equals(field.ConstantValue,roleValue.Value))?.Name;
                    if(role is null)continue;
                    var display=attribute.NamedArguments.FirstOrDefault(pair=>pair.Key=="EntityName").Value.Value as string;
                    var description=attribute.NamedArguments.FirstOrDefault(pair=>pair.Key=="Description").Value.Value as string;
                    roles.Add(new(entity.ToDisplayString(),string.IsNullOrWhiteSpace(display)?entity.Name:display!,role,description));
                }
                return new(id,roles.ToArray());
            }
            receiver=member.Expression;
        }
        return null;
    }
    private sealed record RoleEndpoint(string Id,Role[] Roles);
    private sealed record Role(string Entity,string Name,string RoleName,string? Description);
}
