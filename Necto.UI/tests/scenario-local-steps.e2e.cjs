const { run } = require('./qa-fixture.cjs')

run(async ({ p, assert, builder, add, closeEditor, execute, save, saved, calls }) => {
  await builder()
  await add('Invoice rows')
  const picker = p.locator('.endpoint-options')
  const editor = p.getByRole('dialog', { name: 'Edit step' })
  await editor.getByRole('button', { name: '+ Next request', exact: true }).click()
  await picker.getByRole('button', { name: /Pick random/ }).click()
  assert.notEqual(await editor.getByLabel('Random source step').inputValue(), '')
  await editor.getByLabel('Step name').fill('Pick one invoice')
  await closeEditor()

  await p.getByRole('button', { name: '+ Add request', exact: true }).click()
  await picker.getByRole('button', { name: /Expression/ }).click()
  await editor.getByLabel('Expression code').fill('return { ready: true };')
  await closeEditor()
  await save()
  assert.deepEqual((await saved()).steps.map(step => step.method), ['GET', 'LOCAL', 'LOCAL'])
  await execute(3)
  assert.deepEqual(calls.map(call => call.path), ['/rows'])
  await p.getByRole('button', { name: 'View response for Pick one invoice' }).click()
  const result = p.locator('.step-dialog[open]')
  await result.getByRole('button', { name: 'Result', exact: true }).waitFor()
  await result.locator('.json-preview').waitFor()
})
