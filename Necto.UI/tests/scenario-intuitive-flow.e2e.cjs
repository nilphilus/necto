const { run } = require('./qa-fixture.cjs')

run(async ({ p, assert, builder, save, closeEditor, review, calls }) => {
  await p.route('**/openapi.json', async (route) => {
    const response = await route.fetch()
    const document = await response.json()
    document.paths['/invoices'].post.deprecated = true
    document.paths['/invoices'].post.parameters = [
      { in: 'query', name: 'region', required: true, schema: { type: 'string' } },
      { in: 'query', name: 'department', required: true, schema: { type: 'string' } },
    ]
    await route.fulfill({ response, json: document })
  })
  await p.reload()
  await builder()
  const actions = p.getByRole('group', { name: 'Current scenario actions' })
  assert.equal(await actions.getByRole('button', { name: 'Save', exact: true }).count(), 1)
  assert.equal(await actions.getByRole('button', { name: 'Review & run', exact: true }).count(), 1)
  assert.equal(await actions.getByRole('button', { name: 'Run', exact: true }).count(), 1)
  assert.equal(await p.getByLabel('Saved builder scenarios').count(), 0)
  const map = p.getByRole('region', { name: 'Scenario map' })
  const changeName = async name => {
    await p.getByRole('button', { name: 'Scenario details', exact: true }).click()
    const details = p.getByRole('dialog', { name: 'Scenario details' })
    await details.getByRole('textbox', { name: 'Scenario name' }).fill(name)
    await details.getByRole('button', { name: 'Done' }).click()
  }
  const mapTop = (await map.boundingBox()).y
  const alert = p.locator('.builder-error-notice').getByRole('alert')
  await changeName('')
  await alert.waitFor()
  assert.equal((await map.boundingBox()).y, mapTop)
  await p.getByRole('button', { name: 'Dismiss error' }).click()
  await alert.waitFor({ state: 'hidden' })
  assert.equal(await actions.getByRole('button', { name: 'Save', exact: true }).isDisabled(), true)
  await changeName('Untitled scenario')
  await changeName('')
  await alert.waitFor()
  await changeName('Untitled scenario')
  await alert.waitFor({ state: 'hidden' })
  await p.setViewportSize({ width: 390, height: 844 })
  assert.equal(await p.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
  assert.equal(await actions.getByRole('button', { name: 'Save', exact: true }).isVisible(), true)
  await p.setViewportSize({ width: 1440, height: 1000 })
  const addFirst = p.getByRole('region', { name: 'Scenario map' }).getByRole('button', { name: '+ Add request', exact: true })
  assert.equal(await p.getByRole('button', { name: '+ Add request', exact: true }).count(), 1)
  await addFirst.click()
  const search = p.getByRole('searchbox', { name: 'Find endpoint' })
  await search.fill('invoice')
  assert.ok(await p.locator('.endpoint-result').count() > 1)
  await search.press('ArrowDown')
  assert.match(await p.locator('.endpoint-result:focus').innerText(), /Create invoice/)
  await p.keyboard.press('ArrowDown')
  assert.match(await p.locator('.endpoint-result:focus').innerText(), /Invoice rows/)
  await p.keyboard.press('ArrowUp')
  await p.keyboard.press('Enter')
  const editor = p.getByRole('dialog', { name: 'Edit step', exact: true })
  const request = editor.getByRole('region', { name: 'Request inputs', exact: true })
  const connections = editor.getByRole('button', { name: /^Edit connection/ })
  assert.ok((await request.boundingBox()).y < (await connections.boundingBox()).y)

  await request.getByLabel('Source for customerId').selectOption('expression')
  await closeEditor()
  await p.getByRole('button', { name: 'Go to step', exact: true }).click()
  const expression = editor.getByLabel('Expression code')
  assert.equal(await expression.evaluate((element) => element === document.activeElement), true)
  await expression.fill('return 42;')
  await save()

  await closeEditor()
  await actions.getByRole('button', { name: 'Run', exact: true }).click()
  let dialog = p.getByRole('dialog', { name: 'Resolve run issues' })
  assert.equal(calls.length, 0)
  await dialog.getByRole('alert').filter({ hasText: 'region is required' }).waitFor()
  await dialog.getByRole('alert').filter({ hasText: 'department is required' }).waitFor()
  await dialog.locator('.run-issue').filter({ hasText: 'region is required' })
    .getByRole('button', { name: 'Go to step', exact: true }).click()
  const region = editor.locator('[data-parameter="query:region"] input')
  assert.equal(await region.evaluate((element) => element === document.activeElement), true)
  await region.fill('EU')
  await editor.locator('[data-parameter="query:department"] input').fill('QA')
  await save()

  dialog = await review()
  await dialog.getByText('Deprecated endpoint', { exact: true }).waitFor()
  const limit = dialog.getByRole('spinbutton', { name: 'Parallel requests for this run' })
  await limit.fill('1')
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  await p.getByTitle('All changes saved').waitFor()
  dialog = await review()
  assert.equal(await limit.inputValue(), '4')
  await limit.fill('1')
  await dialog.getByRole('button', { name: 'Run scenario', exact: true }).click()
  await p.locator('.builder-run-status').filter({ hasText: '1 / 1 completed' }).waitFor()
  assert.equal(calls.length, 1)

  await p.locator('.map-node').filter({ hasText: 'Create invoice' }).dblclick()
  await editor.waitFor()
  await closeEditor()
  await p.getByRole('button', { name: 'Add next request', exact: true }).click()
  await p.getByText('Add after: Create invoice', { exact: true }).waitFor()
  await p.keyboard.press('Escape')
  await p.getByRole('button', { name: 'View response for Create invoice', exact: true }).click()
  await p.getByRole('dialog', { name: 'Step response', exact: true }).waitFor()
  await p.keyboard.press('Escape')
  await p.getByRole('button', { name: '← Scenarios', exact: true }).click()
  await p.getByRole('button', { name: /^Run Builder scenario / }).click()
  await p.locator('.builder-run-status').filter({ hasText: '1 / 1 completed' }).waitFor()
  assert.equal(await p.getByRole('dialog', { name: 'Review scenario run' }).count(), 0)
  assert.equal(calls.length, 2)
  await p.getByRole('button', { name: '← Scenarios', exact: true }).click()
  await p.getByRole('button', { name: 'New scenario', exact: true }).click()
  assert.equal(await p.locator('.scenario-title').innerText(), 'Untitled scenario')

})
